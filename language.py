"""Deutsch and English for the application UI."""

import ctypes
import locale
import sys

LANGUAGE_LABELS = {'de': 'Deutsch', 'en': 'English'}
_current_language = 'de'


def system_language():
    if sys.platform == 'win32':
        language_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        return 'de' if (language_id & 0x3ff) == 0x07 else 'en'
    name, _ = locale.getlocale()
    return 'de' if name and name.split('_', 1)[0].lower() == 'de' else 'en'


def configure_language(preference=None):
    global _current_language
    _current_language = (
        preference if isinstance(preference, str) and preference in LANGUAGE_LABELS else system_language()
    )
    return _current_language


def translate(message, *values):
    text = ENGLISH.get(message, message) if _current_language == 'en' else message
    return text.format(*values) if values else text


